namespace ProCalendar.Maui.Core.Enums
{
    /// <summary>
    /// Defines the display mode for the calendar control.
    /// </summary>
    public enum CalendarViewMode
    {
        /// <summary>
        /// Displays a full month view with all days visible.
        /// </summary>
        Month,

        /// <summary>
        /// Displays a week view with 7 days.
        /// </summary>
        Week,

        /// <summary>
        /// Displays a single day view with hourly breakdown.
        /// </summary>
        Day,

        /// <summary>
        /// Displays an agenda/list view of upcoming events.
        /// </summary>
        Agenda
    }
}
